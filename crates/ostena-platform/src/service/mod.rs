//! Agent service registration and runtime integration (ADR-0007): Windows
//! SCM and systemd, behind one trait.

use std::path::{Path, PathBuf};

#[cfg(target_os = "linux")]
mod systemd;
#[cfg(windows)]
mod windows;

#[cfg(target_os = "linux")]
pub use systemd::notify;
#[cfg(windows)]
pub use windows::{SERVICE_NAME, ServiceContext, run_service};

/// Name of the systemd unit.
pub const UNIT_NAME: &str = "ostena-agent.service";
/// Linux service user.
pub const SERVICE_USER: &str = "ostena";
/// Restarts allowed within [`RESTART_WINDOW_SECS`] before the service stays
/// stopped.
pub const RESTART_BURST: u32 = 3;
/// Window of [`RESTART_BURST`], in seconds.
pub const RESTART_WINDOW_SECS: u64 = 600;
/// Delay before an automatic restart, in seconds.
pub const RESTART_DELAY_SECS: u64 = 5;

/// Stable error codes of the agent platform layer.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Code {
    /// Administrator (root) rights needed.
    Privileges,
    /// Installation failed.
    Install,
    /// Uninstallation failed.
    Uninstall,
    /// Service state unavailable.
    State,
    /// Service runtime failure.
    Runtime,
}

impl Code {
    /// The code as written in messages, e.g. `AGT-E001`.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Privileges => "AGT-E001",
            Self::Install => "AGT-E002",
            Self::Uninstall => "AGT-E003",
            Self::State => "AGT-E004",
            Self::Runtime => "AGT-E005",
        }
    }
}

/// A platform failure, with a stable code and a French message.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("[{}] {message}", code.as_str())]
pub struct PlatformError {
    /// Stable code.
    pub code: Code,
    /// What went wrong.
    pub message: String,
}

impl PlatformError {
    pub(crate) fn new(code: Code, message: impl Into<String>) -> Self {
        Self {
            code,
            message: message.into(),
        }
    }
}

/// What to install.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InstallOptions {
    /// The `ostena` executable.
    pub executable: PathBuf,
    /// Configuration file.
    pub config: PathBuf,
    /// Private key and anti-replay journal directory, from the configuration,
    /// so that their permissions can be set for the service account.
    pub private_key: Option<PathBuf>,
    /// Anti-replay journal directory.
    pub state_dir: Option<PathBuf>,
    /// Start the service once installed.
    pub start: bool,
}

/// State reported by the service manager.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ServiceState {
    /// Not registered.
    NotInstalled,
    /// Registered, not running.
    Stopped,
    /// Starting.
    Starting,
    /// Running.
    Running,
    /// Stopping.
    Stopping,
    /// Stopped after failures (restart limit reached on Linux).
    Failed,
    /// Anything else, as reported.
    Other(String),
}

/// Registration of the agent with the operating system service manager.
pub trait ServiceManager {
    /// Registers (or updates) the service, sets the permissions of its
    /// files, and starts it if asked. Idempotent.
    ///
    /// # Errors
    ///
    /// [`PlatformError`] with `AGT-E001` (rights) or `AGT-E002`.
    fn install(&self, options: &InstallOptions) -> Result<(), PlatformError>;

    /// Stops and unregisters the service; keeps its data and account.
    ///
    /// # Errors
    ///
    /// [`PlatformError`] with `AGT-E001` or `AGT-E003`.
    fn uninstall(&self) -> Result<(), PlatformError>;

    /// Current state.
    ///
    /// # Errors
    ///
    /// [`PlatformError`] with `AGT-E004`.
    fn state(&self) -> Result<ServiceState, PlatformError>;
}

/// The service manager of this platform.
///
/// # Errors
///
/// `AGT-E004` on a platform without a supported service manager.
pub fn service_manager() -> Result<&'static dyn ServiceManager, PlatformError> {
    #[cfg(windows)]
    {
        Ok(&windows::Scm)
    }
    #[cfg(target_os = "linux")]
    {
        Ok(&systemd::Systemd)
    }
    #[cfg(not(any(windows, target_os = "linux")))]
    {
        Err(PlatformError::new(
            Code::State,
            "gestionnaire de services non pris en charge sur cette plateforme",
        ))
    }
}

/// The hardened systemd unit (systemd 247, Debian 11, and later).
pub fn systemd_unit(executable: &Path, config: &Path) -> String {
    format!(
        "\
# Generated by `ostena agent install`. Hardening: see ADR-0007.
[Unit]
Description=Ostena gateway agent
Documentation=https://github.com/Phdhebde/Ostena
Wants=network-online.target
After=network-online.target
# At most {burst} automatic restarts in {window} s, then the unit stays failed.
StartLimitIntervalSec={window}
StartLimitBurst={burst}

[Service]
Type=notify
NotifyAccess=main
ExecStart={exe} agent run --config {config}
Restart=on-failure
RestartSec={delay}
TimeoutStopSec=330
User={user}
Group={user}
UMask=0077

StateDirectory=ostena
StateDirectoryMode=0700
RuntimeDirectory=ostena
RuntimeDirectoryMode=0700

NoNewPrivileges=yes
CapabilityBoundingSet=
AmbientCapabilities=
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
ProtectProc=invisible
ProcSubset=pid
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
RemoveIPC=yes
KeyringMode=private
SystemCallArchitectures=native
SystemCallFilter=@system-service
SystemCallFilter=~@privileged @resources
SystemCallErrorNumber=EPERM
# AF_NETLINK: listing the host interfaces (scope floor).
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK

[Install]
WantedBy=multi-user.target
",
        burst = RESTART_BURST,
        window = RESTART_WINDOW_SECS,
        delay = RESTART_DELAY_SECS,
        exe = executable.display(),
        config = config.display(),
        user = SERVICE_USER,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unit_is_hardened_and_bounded() {
        let unit = systemd_unit(
            Path::new("/usr/local/bin/ostena"),
            Path::new("/etc/ostena/ostena.toml"),
        );
        for line in [
            "Type=notify",
            "ExecStart=/usr/local/bin/ostena agent run --config /etc/ostena/ostena.toml",
            "User=ostena",
            "StartLimitIntervalSec=600",
            "StartLimitBurst=3",
            "Restart=on-failure",
            "RuntimeDirectoryMode=0700",
            "StateDirectoryMode=0700",
            "NoNewPrivileges=yes",
            "ProtectSystem=strict",
            "PrivateTmp=yes",
            "CapabilityBoundingSet=",
            "AmbientCapabilities=",
            "MemoryDenyWriteExecute=yes",
            "RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK",
            "UMask=0077",
        ] {
            assert!(unit.lines().any(|l| l == line), "missing {line}");
        }
        // Grace period of the agent (at most 300 s) fits in the stop timeout.
        assert!(unit.contains("TimeoutStopSec=330"));
    }

    /// Writes the unit for `systemd-analyze verify` on the oldest supported
    /// systemd (Debian 11): `OSTENA_UNIT_OUT=<file> cargo test -p
    /// ostena-platform -- --ignored write_unit`.
    #[test]
    #[ignore = "writes a file; run by the CI unit verification"]
    fn write_unit_for_verification() {
        let out = std::env::var_os("OSTENA_UNIT_OUT").expect("OSTENA_UNIT_OUT");
        let unit = systemd_unit(
            Path::new("/usr/local/bin/ostena"),
            Path::new("/etc/ostena/ostena.toml"),
        );
        std::fs::write(out, unit).unwrap();
    }

    #[test]
    fn codes() {
        assert_eq!(Code::Privileges.as_str(), "AGT-E001");
        let e = PlatformError::new(Code::Install, "échec");
        assert_eq!(e.to_string(), "[AGT-E002] échec");
    }
}
